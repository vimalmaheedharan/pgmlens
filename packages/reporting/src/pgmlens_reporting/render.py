"""Markdown rendering with visible evidence."""

from __future__ import annotations

from .briefing import Briefing


def render_markdown(briefing: Briefing) -> str:
    by_id = {f.id: f for f in briefing.facts}
    cited: list[str] = []
    lines = [
        f"# {briefing.program}: executive briefing",
        f"_As of {briefing.as_of:%B %d, %Y}_",
        "",
        f"**{briefing.headline}**",
    ]
    for section in briefing.sections:
        if not section.claims:
            continue
        lines += ["", f"## {section.title}"]
        for claim in section.claims:
            refs = " ".join(f"[{i}]" for i in claim.fact_ids)
            lines.append(f"- {claim.text} {refs}")
            cited.extend(i for i in claim.fact_ids if i not in cited)
    lines += ["", "## Evidence"]
    for fact_id in cited:
        fact = by_id.get(fact_id)
        if fact is None:
            continue
        issues = f" Issues: {', '.join(fact.evidence)}." if fact.evidence else ""
        lines.append(f"- [{fact_id}] {fact.text}{issues}")
    footer = "Generated by PGM Lens"
    footer += " with LLM phrasing" if briefing.source == "llm" else " (deterministic)"
    lines += ["", f"_{footer}. Every statement above is backed by computed facts._"]
    if briefing.warnings:
        lines += ["", *[f"> Note: {w}" for w in briefing.warnings]]
    return "\n".join(lines)
